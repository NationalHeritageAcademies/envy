// Rasterize the menu-bar / system-tray glyph and emit it as a base64 TS module
// (src/app/tray-icons.ts) so the main process can build a nativeImage at runtime
// without shipping a separate asset file. Run via `npm run icons`.
//
//   - macOS wants a *template* image: pure black on transparent, which the OS
//     recolors to match the menu bar (light/dark). → the "mono" glyph.
//   - Windows/Linux trays don't recolor, so they get the brand-green eye. → "color".
//
// The glyph is the Envy eye distilled to a ring + pupil so it stays legible at 16px.

import { Resvg } from '@resvg/resvg-js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const glyph = (stroke, fill) => `
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <circle cx="16" cy="16" r="11" fill="none" stroke="${stroke}" stroke-width="3"/>
  <circle cx="16" cy="16" r="4.5" fill="${fill}"/>
</svg>`;

const mono = glyph('#000000', '#000000');
const color = glyph('#10b981', '#10b981');

const png = (svg, size) =>
  new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng().toString('base64');

const out = `// AUTO-GENERATED by scripts/build-tray-icons.mjs — do not edit by hand.
// Base64 PNGs for the tray/menu-bar icon. Run \`npm run icons\` to regenerate.

/** Black-on-transparent template glyph (macOS menu bar recolors it). */
export const TRAY_MONO_16 = '${png(mono, 16)}';
export const TRAY_MONO_32 = '${png(mono, 32)}';

/** Brand-green glyph for Windows/Linux trays (no OS recoloring). */
export const TRAY_COLOR_16 = '${png(color, 16)}';
export const TRAY_COLOR_32 = '${png(color, 32)}';
`;

writeFileSync(resolve(root, 'src/app/tray-icons.ts'), out);
console.log('Wrote src/app/tray-icons.ts (tray glyph @16/@32, mono + color)');
